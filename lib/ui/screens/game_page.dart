  Future<void> _enableVoice() async {
    final bloc = context.read<GameBloc>();
    final latestState = bloc.state;
    if (_voiceBusy ||
        !_supportsVoice(latestState) ||
        !_canStartVoice(latestState as GamePlaying)) {
      return;
    }
    setState(() {
      _voiceBusy = true;
      _voiceSetupFailed = false;
    });
    try {
      final session = widget.voiceSessionFactory!(
        bloc: bloc,
        controlledPlayer: latestState.humanPlayer!,
      );
      _voiceSession = session;
      _voiceState = session.state;
      _voiceSubscription = session.states.listen(_onVoiceStateChanged);
      await session.enableAfterDisclosure();
      if (mounted) setState(() => _voiceState = session.state);
    } catch (_) {
      final failedSession = _voiceSession;
      _voiceSession = null;
      unawaited(_voiceSubscription?.cancel());
      _voiceSubscription = null;
      if (failedSession != null) unawaited(failedSession.dispose());
      if (mounted) setState(() => _voiceSetupFailed = true);
    } finally {
      if (mounted) setState(() => _voiceBusy = false);
    }
  }

  Future<void> _listenOnce() async {
    final session = _voiceSession;
    if (session == null || _voiceBusy) return;
    setState(() => _voiceBusy = true);
    try {
      await session.listenOnce();
    } catch (_) {
      // The session maps operational failures to stable non-sensitive states.
    } finally {
      if (mounted) setState(() => _voiceBusy = false);
    }
  }

  Future<void> _replayVoiceReply() async {
    final session = _voiceSession;
    if (session == null || _voiceBusy) return;
    setState(() => _voiceBusy = true);
    try {
      await session.replayPendingReply();
    } catch (_) {
      // The session maps replay failures to stable non-sensitive states.
    } finally {
      if (mounted) setState(() => _voiceBusy = false);
    }
  }

  void _onVoiceStateChanged(VoiceInteractionState state) {
    if (mounted) setState(() => _voiceState = state);
  }

  void _onGameStateChanged(GameState state) {
    final session = _voiceSession;
    if (session == null) return;
    unawaited(
      session.updateAvailability(
        appIsActive: _appIsActive,
      ),
    );
  }

  String _voiceStatus(
    AppLocalizations l10n,
    VoiceInteractionState state,
  ) {
    return switch (state.phase) {
      VoiceInteractionPhase.disabled => l10n.meditationVoiceDisabled,
      VoiceInteractionPhase.requestingPermission ||
      VoiceInteractionPhase.initializing =>
        l10n.meditationVoicePreparing,
      VoiceInteractionPhase.ready => l10n.meditationVoiceReady,
      VoiceInteractionPhase.listening => l10n.meditationVoiceListening,
      VoiceInteractionPhase.processing => l10n.meditationVoiceProcessing,
      VoiceInteractionPhase.speaking => l10n.meditationVoiceSpeaking,
      VoiceInteractionPhase.awaitingReplay => l10n.meditationVoiceReplay,
      VoiceInteractionPhase.permissionDenied ||
      VoiceInteractionPhase.permissionPermanentlyDenied ||
      VoiceInteractionPhase.restricted =>
        l10n.meditationVoicePermissionDenied,
      VoiceInteractionPhase.unavailable => l10n.meditationVoiceUnavailable,
      VoiceInteractionPhase.interrupted => l10n.gameVoiceWaitForTurn,
      VoiceInteractionPhase.failed ||
      VoiceInteractionPhase.disposed =>
        l10n.meditationVoiceFailed,
    };
  }

  void _handlePositionTapped(
    BuildContext context,
    Position position,
  ) {
    context.read<GameBloc>().add(ActivateBoardPositionEvent(position));
  }

  void _showGameOverDialog(BuildContext context, GameOver state) {
    final l10n = AppLocalizations.of(context)!;
    WidgetsBinding.instance.addPostFrameCallback((_) {
      showGameOverDialog(
        context,
        winner: state.winner,
        gameResult: state.gameResult!,
        onRestart: () {
          Navigator.of(context).pop();
          context.read<GameBloc>().add(const RestartGameEvent());
        },
        onExit: () {
          Navigator.of(context).pop();
          Navigator.of(context).pop();
        },
        onReplay: state.moveHistory.isNotEmpty
            ? () {
                Navigator.of(context).pop();
                Navigator.of(context).push(
                  MaterialPageRoute(
                    builder: (context) => GameReplayPage(
                      moveHistory: state.moveHistory,
                      startingPlayer: state.firstPlayer ?? PieceType.black,
                      gameTitle: state.mode == GameMode.pvp
                          ? l10n.pvpReplayTitle
                          : l10n.pveReplayTitle,
                    ),
                  ),
                );
              }
            : null,
      );
    });
  }

  void _showRestartConfirmation(BuildContext context) {
    final l10n = AppLocalizations.of(context)!;
    showDialog(
      context: context,
      builder: (dialogContext) => AlertDialog(
        title: Text(l10n.restartConfirmTitle),
        content: Text(l10n.restartConfirmBody),
        actions: [
          TextButton(
            onPressed: () => Navigator.of(dialogContext).pop(),
            child: Text(l10n.cancel),
          ),
          TextButton(
            onPressed: () {
              Navigator.of(dialogContext).pop();
              context.read<GameBloc>().add(const RestartGameEvent());
            },
            child: Text(l10n.confirm),
          ),
        ],
      ),
    );
  }
}
